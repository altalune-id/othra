func TestOnlyKernelDBBeginsTransactions(t *testing.T) {
	root := moduleRoot(t)
	own := filepath.Join(root, "internal", "kernel", "db")
	var bad []string
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			switch d.Name() {
			case "node_modules", "gen", "testdata", ".git", ".agents", ".claude", ".superpowers":
				return filepath.SkipDir
			}
			if path == own {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") || strings.HasSuffix(path, "_templ.go") {
			return nil
		}
		rel, _ := filepath.Rel(root, path)
		bad = append(bad, txViolations(t, path, rel)...)
		return nil
	})
	require.NoError(t, err)
	require.Empty(t, bad, "use db.Reader, db.Writer, db.InTx or a db.Transactor instead")
}

func TestTxViolationsFindsEachKind(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "store.go")
	src := `package store

import (
	"context"
	"database/sql"

	"github.com/go-jet/jet/v2/qrm"
)

type s struct{ w *sql.DB }

func (x s) reader(ctx context.Context) qrm.DB { return x.w }
func (x s) writer(ctx context.Context) qrm.DB { return x.w }
func (x s) txAcquire(ctx context.Context) (*sql.Tx, error) { return x.w.BeginTx(ctx, nil) }
func endTx(tx *sql.Tx) error { return tx.Commit() }
func (x s) begin() (*sql.Tx, error) { return x.w.Begin() }
func (x s) other(ctx context.Context) (int, error) { return 0, nil }
func (x s) use(ctx context.Context, t interface{ RunInTx(context.Context, func(context.Context) error) error }) error {
	_ = db.RunInTx(ctx, db.Pool{}, nil)
	return t.RunInTx(ctx, nil)
}
`
	require.NoError(t, os.WriteFile(path, []byte(src), 0o600))
	got := txViolations(t, path, "store.go")
	require.Len(t, got, 7, got)

	gen := filepath.Join(dir, "gen.go")
	require.NoError(t, os.WriteFile(gen, []byte("// Code generated by x. DO NOT EDIT.\n\n"+src), 0o600))
	require.Empty(t, txViolations(t, gen, "gen.go"), "generated files are skipped")
}

func txViolations(t *testing.T, path, rel string) []string {
	t.Helper()
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
	require.NoError(t, err)
	if ast.IsGenerated(f) {
		return nil
	}
	var out []string
	ast.Inspect(f, func(n ast.Node) bool {
		switch n := n.(type) {
		case *ast.FuncDecl:
			switch n.Name.Name {
			case "txAcquire", "endTx":
				out = append(out, rel+": defines "+n.Name.Name)
			case "reader", "writer":
				if returnsQueryable(n) {
					out = append(out, rel+": defines "+n.Name.Name)
				}
			}
		case *ast.CallExpr:
			sel, ok := n.Fun.(*ast.SelectorExpr)
			if !ok {
				return true
			}
			pkg, _ := sel.X.(*ast.Ident)
			if sel.Sel.Name == "BeginTx" || sel.Sel.Name == "Begin" || (sel.Sel.Name == "RunInTx" && pkg != nil && pkg.Name == "db") {
				out = append(out, fmt.Sprintf("%s:%d: calls %s", rel, fset.Position(n.Pos()).Line, sel.Sel.Name))
			}
		}
		return true
	})
	return out
}

func returnsQueryable(fn *ast.FuncDecl) bool {
	if fn.Type.Results == nil {
		return false
	}
	for _, r := range fn.Type.Results.List {
		switch typ := r.Type.(type) {
		case *ast.SelectorExpr:
			if typ.Sel.Name == "DB" || typ.Sel.Name == "Tx" {
				return true
			}
		case *ast.StarExpr:
			if sel, ok := typ.X.(*ast.SelectorExpr); ok && (sel.Sel.Name == "DB" || sel.Sel.Name == "Tx") {
				return true
			}
		}
	}
	return false
}

func moduleRoot(t *testing.T) string {
	t.Helper()
	dir, err := os.Getwd()
	require.NoError(t, err)
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir
		}
		parent := filepath.Dir(dir)
		require.NotEqual(t, dir, parent, "go.mod not found")
		dir = parent
	}
}
