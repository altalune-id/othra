// Command gen-apperror regenerates apperror/codes.gen.go from apperror/codes.json.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"os"
	"regexp"
)

type entry struct {
	Code    string   `json:"code"`
	Name    string   `json:"name"`
	Kind    string   `json:"kind"`
	Params  []string `json:"params"`
	Reasons []string `json:"reasons"`
}

//nolint:gochecknoglobals // immutable lookup tables.
var (
	codeRE  = regexp.MustCompile(`^[A-Z]{3}\d{3}$`)
	nameRE  = regexp.MustCompile(`^[A-Z][A-Za-z0-9]*$`)
	snakeRE = regexp.MustCompile(`^[a-z][a-z0-9]*(_[a-z0-9]+)*$`)
	kinds   = map[string]string{
		"invalid":             "KindInvalid",
		"not_found":           "KindNotFound",
		"already_exists":      "KindAlreadyExists",
		"unauthenticated":     "KindUnauthenticated",
		"forbidden":           "KindForbidden",
		"failed_precondition": "KindFailedPrecondition",
		"internal":            "KindInternal",
		"resource_exhausted":  "KindResourceExhausted",
	}
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-apperror:", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := os.ReadFile("apperror/codes.json")
	if err != nil {
		return err
	}
	entries, err := parse(raw)
	if err != nil {
		return err
	}
	out, err := render(entries)
	if err != nil {
		return err
	}
	return os.WriteFile("apperror/codes.gen.go", out, 0o644) //nolint:gosec // G306: generated source is committed, not secrets.
}

func parse(raw []byte) ([]entry, error) {
	var entries []entry
	if err := json.Unmarshal(raw, &entries); err != nil {
		return nil, fmt.Errorf("codes.json: %w", err)
	}
	if len(entries) == 0 {
		return nil, errors.New("codes.json: no entries")
	}
	codes := map[string]bool{}
	names := map[string]bool{}
	for _, e := range entries {
		switch {
		case !codeRE.MatchString(e.Code):
			return nil, fmt.Errorf("code %q: want three capitals and three digits", e.Code)
		case codes[e.Code]:
			return nil, fmt.Errorf("duplicate code %q", e.Code)
		case !nameRE.MatchString(e.Name):
			return nil, fmt.Errorf("%s: name %q: want a Go identifier starting with a capital", e.Code, e.Name)
		case names[e.Name]:
			return nil, fmt.Errorf("%s: duplicate name %q", e.Code, e.Name)
		case kinds[e.Kind] == "":
			return nil, fmt.Errorf("%s: kind %q: unknown", e.Code, e.Kind)
		}
		codes[e.Code], names[e.Name] = true, true
		// meta.reason carries the entry's reasons, so no param may take that name.
		if err := snakeSet(e.Code, "param", e.Params, "reason"); err != nil {
			return nil, err
		}
		if err := snakeSet(e.Code, "reason", e.Reasons, ""); err != nil {
			return nil, err
		}
	}
	return entries, nil
}

func snakeSet(code, what string, values []string, reserved string) error {
	seen := map[string]bool{}
	for _, v := range values {
		switch {
		case !snakeRE.MatchString(v):
			return fmt.Errorf("%s: %s %q: want snake_case", code, what, v)
		case v == reserved:
			return fmt.Errorf("%s: %s %q: reserved", code, what, v)
		case seen[v]:
			return fmt.Errorf("%s: duplicate %s %q", code, what, v)
		}
		seen[v] = true
	}
	return nil
}

func render(entries []entry) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by gen-apperror from apperror/codes.json; DO NOT EDIT.\n\n")
	b.WriteString("package apperror\n\n")
	b.WriteString("// Error codes: <DOM><NNN>, append-only; 900-999 is reserved for internal failures.\nconst (\n")
	writeGrouped(&b, entries, func(e entry) string { return fmt.Sprintf("\tCode%s Code = %q\n", e.Name, e.Code) })
	b.WriteString(")\n\nvar kinds = map[Code]Kind{\n")
	writeGrouped(&b, entries, func(e entry) string { return fmt.Sprintf("\tCode%s: %s,\n", e.Name, kinds[e.Kind]) })
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

func writeGrouped(b *bytes.Buffer, entries []entry, line func(entry) string) {
	prefix := ""
	for _, e := range entries {
		if prefix != "" && e.Code[:3] != prefix {
			b.WriteString("\n")
		}
		prefix = e.Code[:3]
		b.WriteString(line(e))
	}
}
