package main

import (
	"os"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestGenerated_MatchesCatalog(t *testing.T) {
	raw, err := os.ReadFile("../../apperror/codes.json")
	require.NoError(t, err)
	entries, err := parse(raw)
	require.NoError(t, err)
	want, err := render(entries)
	require.NoError(t, err)

	got, err := os.ReadFile("../../apperror/codes.gen.go")
	require.NoError(t, err)
	assert.Equal(t, string(want), string(got), "apperror/codes.gen.go is stale; run make generate")
}

func TestParse_Rejects(t *testing.T) {
	for name, tc := range map[string]struct {
		json string
		want string
	}{
		"bad json":         {`{`, "codes.json"},
		"empty":            {`[]`, "no entries"},
		"code shape":       {`[{"code":"G01","name":"A","kind":"invalid"}]`, `code "G01"`},
		"duplicate code":   {`[{"code":"GEN001","name":"A","kind":"invalid"},{"code":"GEN001","name":"B","kind":"invalid"}]`, `duplicate code "GEN001"`},
		"name shape":       {`[{"code":"GEN001","name":"lower","kind":"invalid"}]`, `name "lower"`},
		"duplicate name":   {`[{"code":"GEN001","name":"A","kind":"invalid"},{"code":"GEN002","name":"A","kind":"invalid"}]`, `duplicate name "A"`},
		"unknown kind":     {`[{"code":"GEN001","name":"A","kind":"teapot"}]`, `kind "teapot"`},
		"param shape":      {`[{"code":"GEN001","name":"A","kind":"invalid","params":["Max"]}]`, `param "Max"`},
		"duplicate param":  {`[{"code":"GEN001","name":"A","kind":"invalid","params":["max","max"]}]`, `duplicate param "max"`},
		"reserved param":   {`[{"code":"GEN001","name":"A","kind":"invalid","params":["reason"]}]`, `param "reason"`},
		"reason shape":     {`[{"code":"GEN001","name":"A","kind":"invalid","reasons":["too-long"]}]`, `reason "too-long"`},
		"duplicate reason": {`[{"code":"GEN001","name":"A","kind":"invalid","reasons":["x","x"]}]`, `duplicate reason "x"`},
	} {
		t.Run(name, func(t *testing.T) {
			_, err := parse([]byte(tc.json))
			require.Error(t, err)
			assert.Contains(t, err.Error(), tc.want)
		})
	}
}

func TestRender_ConstantsAndKinds(t *testing.T) {
	out, err := render([]entry{
		{Code: "GEN001", Name: "TenantMissing", Kind: "unauthenticated"},
		{Code: "WHK002", Name: "WebhookInvalidURL", Kind: "invalid", Reasons: []string{"https_required"}},
	})
	require.NoError(t, err)
	s := string(out)
	assert.Contains(t, s, "// Code generated by gen-apperror from apperror/codes.json; DO NOT EDIT.")
	assert.Contains(t, s, "CodeTenantMissing Code = \"GEN001\"\n\n\tCodeWebhookInvalidURL", "a blank line between code prefixes")
	assert.Contains(t, s, "CodeWebhookInvalidURL: KindInvalid,")
	assert.Contains(t, s, "CodeTenantMissing: KindUnauthenticated,")
}

func TestRun_WritesTheGeneratedFile(t *testing.T) {
	t.Chdir(t.TempDir())
	require.NoError(t, os.Mkdir("apperror", 0o750))
	require.ErrorIs(t, run(), os.ErrNotExist)

	require.NoError(t, os.WriteFile("apperror/codes.json", []byte(`{`), 0o600))
	require.Error(t, run())

	catalog := `[{"code":"GEN001","name":"TenantMissing","kind":"unauthenticated","params":[],"reasons":[]}]`
	require.NoError(t, os.WriteFile("apperror/codes.json", []byte(catalog), 0o600))
	require.NoError(t, run())
	out, err := os.ReadFile("apperror/codes.gen.go")
	require.NoError(t, err)
	assert.Contains(t, string(out), `CodeTenantMissing Code = "GEN001"`)
}
