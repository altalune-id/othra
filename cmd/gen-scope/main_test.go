func TestGenerated_MatchesCatalog(t *testing.T) {
	catalog, err := os.ReadFile("../../scope/scopes.json")
	require.NoError(t, err)
	want, err := os.ReadFile("../../scope/names.gen.go")
	require.NoError(t, err)

	t.Chdir(t.TempDir())
	require.NoError(t, os.Mkdir("scope", 0o750))
	require.NoError(t, os.WriteFile("scope/scopes.json", catalog, 0o600))
	require.NoError(t, run())

	got, err := os.ReadFile("scope/names.gen.go")
	require.NoError(t, err)
	assert.Equal(t, string(want), string(got), "scope/names.gen.go is stale; run make generate")
}

func TestGenerated_IsGofmtClean(t *testing.T) {
	src, err := os.ReadFile("../../scope/names.gen.go")
	require.NoError(t, err)
	formatted, err := format.Source(src)
	require.NoError(t, err)
	assert.Equal(t, string(formatted), string(src), "gen-scope must write gofmt-formatted source")
}

func TestGenerated_HasOneConstantPerScope(t *testing.T) {
	raw, err := os.ReadFile("../../scope/scopes.json")
	require.NoError(t, err)
	var specs []spec
	require.NoError(t, json.Unmarshal(raw, &specs))
	require.NotEmpty(t, specs)

	gen, err := os.ReadFile("../../scope/names.gen.go")
	require.NoError(t, err)
	for _, s := range specs {
		assert.Regexp(t, `(?m)^\t`+ident(s.Name)+` +=  *"`+regexp.QuoteMeta(s.Name)+`"$`, string(gen))
	}
}

func TestIdent(t *testing.T) {
	for in, want := range map[string]string{
		"org:read":         "OrgRead",
		"apikey:write":     "ApikeyWrite",
		"web-hook:read":    "WebHookRead",
		"api_key:rotate":   "ApiKeyRotate",
		"a::b":             "AB",
		"single":           "Single",
		"":                 "",
		"x:alreadyUpper":   "XAlreadyUpper",
		":leading:trailer": "LeadingTrailer",
	} {
		assert.Equal(t, want, ident(in), "ident(%q)", in)
	}
}

func TestRun_WritesTheGeneratedFile(t *testing.T) {
	t.Chdir(t.TempDir())
	require.ErrorIs(t, run(), os.ErrNotExist)

	require.NoError(t, os.Mkdir("scope", 0o750))
	require.NoError(t, os.WriteFile("scope/scopes.json", []byte(`{`), 0o600))
	require.Error(t, run())

	require.NoError(t, os.WriteFile("scope/scopes.json", []byte(`[{"name":"org:read","level":"org"},{"name":"webhook:write","level":"project"}]`), 0o600))
	require.NoError(t, run())
	out, err := os.ReadFile("scope/names.gen.go")
	require.NoError(t, err)
	assert.Equal(t, `// Code generated by gen-scope from scope/scopes.json; DO NOT EDIT.

package scope

// Scope names, generated from scope/scopes.json.
const (
	OrgRead      = "org:read"
	WebhookWrite = "webhook:write"
)
`, string(out))

	require.NoError(t, os.Remove("scope/names.gen.go"))
	require.NoError(t, os.Mkdir("scope/names.gen.go", 0o750))
	require.Error(t, run(), "an unwritable target fails")
}

func TestMain_ExitsNonZeroOnError(t *testing.T) {
	if os.Getenv("GEN_SCOPE_MAIN") == "1" {
		main()
		return
	}

	t.Chdir(t.TempDir())
	cmd := exec.CommandContext(t.Context(), os.Args[0], "-test.run=^TestMain_ExitsNonZeroOnError$")
	cmd.Env = append(os.Environ(), "GEN_SCOPE_MAIN=1")
	var stderr strings.Builder
	cmd.Stderr = &stderr
	err := cmd.Run()
	var exitErr *exec.ExitError
	require.ErrorAs(t, err, &exitErr)
	assert.Equal(t, 1, exitErr.ExitCode())
	assert.Contains(t, stderr.String(), "gen-scope: open scope/scopes.json")
}

func TestMain_WritesTheGeneratedFile(t *testing.T) {
	t.Chdir(t.TempDir())
	require.NoError(t, os.Mkdir("scope", 0o750))
	require.NoError(t, os.WriteFile("scope/scopes.json", []byte(`[{"name":"org:read","level":"org"}]`), 0o600))

	main()

	out, err := os.ReadFile("scope/names.gen.go")
	require.NoError(t, err)
	assert.Contains(t, string(out), "\tOrgRead = \"org:read\"\n")
}
