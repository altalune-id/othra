// Command gen-scope regenerates scope/names.gen.go from scope/scopes.json.
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"strings"
)

type spec struct {
	Name  string `json:"name"`
	Level string `json:"level"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen-scope:", err)
		os.Exit(1)
	}
}

func run() error {
	raw, err := os.ReadFile("scope/scopes.json")
	if err != nil {
		return err
	}
	var specs []spec
	if err := json.Unmarshal(raw, &specs); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Code generated by gen-scope from scope/scopes.json; DO NOT EDIT.\n\n")
	b.WriteString("package scope\n\n")
	b.WriteString("// Scope names, generated from scope/scopes.json.\nconst (\n")
	for _, s := range specs {
		fmt.Fprintf(&b, "\t%s = %q\n", ident(s.Name), s.Name)
	}
	b.WriteString(")\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return err
	}
	return os.WriteFile("scope/names.gen.go", src, 0o644) //nolint:gosec // G306: generated source is committed, not secrets.
}

func ident(name string) string {
	parts := strings.FieldsFunc(name, func(r rune) bool { return r == ':' || r == '-' || r == '_' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		b.WriteString(p[1:])
	}
	return b.String()
}
